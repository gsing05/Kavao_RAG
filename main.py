"""
FastAPI backend for the Kavao research RAG system.

Run locally with: uvicorn main:app --reload
Then open http://localhost:8000 for the search page, or
http://localhost:8000/docs for the interactive API documentation
(auto-generated by FastAPI -- this is the "looks great to hiring
managers" piece).

This file is the deployment entry point later (Render/Railway/HF
Spaces all know how to run a FastAPI app via uvicorn).
"""

import sys
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import HTMLResponse
from pydantic import BaseModel

sys.path.insert(0, str(Path(__file__).parent / "src"))
from pipeline import ask_kavao  # noqa: E402

app = FastAPI(
    title="Kavao Research API",
    description="Citation-grounded question answering over a curated agricultural "
                 "and nutrition research corpus.",
    version="1.0.0",
)


# --- Request/response schemas (this is what powers the /docs page) ---

class QueryRequest(BaseModel):
    question: str


class SourceRef(BaseModel):
    source: str
    section: str


class QueryResponse(BaseModel):
    answer: str
    sources: list[SourceRef]


# --- Endpoints ---

@app.get("/api/health")
async def health_check():
    """Simple uptime check -- useful once this is deployed."""
    return {"status": "healthy"}


@app.post("/api/query", response_model=QueryResponse)
async def query_research(payload: QueryRequest):
    """Accepts a question, retrieves relevant research context, returns a grounded answer."""
    if not payload.question.strip():
        raise HTTPException(status_code=400, detail="Question cannot be empty.")

    try:
        result = ask_kavao(payload.question)
        return QueryResponse(answer=result["answer"], sources=result["sources"])
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Error processing query: {str(e)}")


# --- A minimal search page at "/", for quick manual testing ---

PAGE_TEMPLATE = """
<!DOCTYPE html>
<html>
<head>
    <title>Kavao Research Search</title>
    <style>
        body { font-family: system-ui, sans-serif; max-width: 700px; margin: 40px auto; padding: 0 20px; }
        input[type=text] { width: 100%; padding: 10px; font-size: 16px; }
        button { padding: 10px 20px; font-size: 16px; margin-top: 10px; cursor: pointer; }
        #answer { margin-top: 20px; padding: 15px; background: #f5f5f5; border-radius: 6px; white-space: pre-wrap; }
        #sources { margin-top: 10px; font-size: 14px; color: #555; }
        #loading { display: none; color: #888; margin-top: 10px; }
        .note { font-size: 13px; color: #888; }
    </style>
</head>
<body>
    <h2>Kavao Research Search</h2>
    <p>Ask a question about the vetted research corpus. Answers are grounded in cited sources.</p>
    <p class="note">API docs: <a href="/docs">/docs</a></p>
    <input type="text" id="question" placeholder="e.g. Does cover cropping affect soil nitrogen?">
    <button onclick="ask()">Ask</button>
    <div id="loading">Searching...</div>
    <div id="answer"></div>
    <div id="sources"></div>

    <script>
        async function ask() {
            const question = document.getElementById('question').value;
            if (!question) return;
            document.getElementById('loading').style.display = 'block';
            document.getElementById('answer').textContent = '';
            document.getElementById('sources').textContent = '';

            const res = await fetch('/api/query', {
                method: 'POST',
                headers: {'Content-Type': 'application/json'},
                body: JSON.stringify({question})
            });
            const data = await res.json();

            document.getElementById('loading').style.display = 'none';

            if (!res.ok) {
                document.getElementById('answer').textContent = 'Error: ' + (data.detail || 'unknown error');
                return;
            }

            document.getElementById('answer').textContent = data.answer;
            const sourcesText = data.sources.map(s => `${s.source} (${s.section})`).join(', ');
            document.getElementById('sources').textContent = data.sources.length
                ? 'Sources: ' + sourcesText
                : '';
        }
    </script>
</body>
</html>
"""


@app.get("/", response_class=HTMLResponse)
async def home():
    return PAGE_TEMPLATE
